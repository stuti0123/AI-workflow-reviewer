"""One CPU-only, offline command:  python scripts/run_all.py
Runs tests, verifies fixtures/freeze, evaluates checkpoint-1 and final on the same frozen set, runs two ablations,
writes machine-readable reports to reports/ and a human summary to reports/summary.md. No network, no API keys."""
import hashlib, json, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PY = sys.executable


def sh(*a, check=True):
    r = subprocess.run([PY, *a], cwd=ROOT, capture_output=True, text=True)
    sys.stdout.write(r.stdout)
    if r.returncode and check:
        sys.stderr.write(r.stderr)
        sys.exit(r.returncode)
    return r


def fx_hash():
    h = hashlib.sha256()
    for f in sorted((ROOT / "fixtures").rglob("*.json")):
        h.update(f.read_bytes())
    return h.hexdigest()


print("== 1. unit + regression tests"); sh("-m", "pytest", "-q", "tests")
print("== 2. fixtures reproducible from seed"); before = fx_hash(); sh("fixtures/generate.py"); assert before == fx_hash(), "fixtures changed on regeneration"
print("== 3. freeze verification"); sh("eval/freeze.py", "verify")
R = ROOT / "reports"
runs = [("baseline", ["--impl-path", "checkpoints/checkpoint1"], None), ("final", [], None),
        ("ablation_no_boundary_points", [], {"include_boundaries": False}),
        ("ablation_no_model_claim_validation", [], {"validate_model_claims": False})]
print("== 4. evaluation (fake client / offline; no real model was used)")
for name, extra, abl in runs:
    for split in ("all", "dev", "heldout"):
        if abl and split != "all":
            continue
        args = ["eval/run_eval.py", "--split", split, "--out", f"reports/{name}_{split}.json" if split != "all" else f"reports/{name}.json", *extra]
        if abl:
            args += ["--ablation", json.dumps(abl)]
        print(f"-- {name} [{split}]"); sh(*args)


def pct(x): return f"{x['count']}/{x['denominator']}"
def row(name, rp):
    d, q = rp["decision_correctness"], rp["finding_quality"]
    return (f"| {name} | {pct(d['status_exact_match'])} | {pct(d['false_passes'])} | {pct(d['false_blocks'])} | {pct(d['incomplete_cases_marked_incomplete'])} | "
            f"{d['abstentions_on_valid']}+{d['abstentions_on_defective']} | {pct(q['defect_artifact_and_rule_correct'])} | {pct(q['counterexample_valid_vs_independent_oracle'])} | "
            f"{pct(q['unsupported_blocker_findings'])} | {rp['resource_use']['fake_client_or_offline']['total_runtime_s']}s |")
hdr = ("| run | status exact | false passes | false blocks | incomplete found | abstain valid+defective | defect+rule ok | counterexample ok | unsupported blockers | runtime |\n"
       "|---|---|---|---|---|---|---|---|---|---|")
L = ["# Evaluation summary (generated by scripts/run_all.py)", "",
     "All numbers: synthetic fixtures, deterministic reviewer, **fake model client only**. Real-model performance: not measured.", "", hdr]
for name in ("baseline", "final"):
    for split in ("all", "dev", "heldout"):
        f = R / (f"{name}_{split}.json" if split != "all" else f"{name}.json")
        L.append(row(f"{name} [{split}]", json.loads(f.read_text())))
for name in ("ablation_no_boundary_points", "ablation_no_model_claim_validation"):
    L.append(row(f"{name} [all]", json.loads((R / f"{name}.json").read_text())))
fin, base, ab = (json.loads((R / f).read_text()) for f in ("final.json", "baseline.json", "ablation_no_boundary_points.json"))
def diffs(a, b, la, lb):
    out = []
    for x, y in zip(a["cases"], b["cases"]):
        if x["predicted"] != y["predicted"] or any(p["matched_with_rule_ref"] != q["matched_with_rule_ref"] for p, q in zip(x["defects"], y["defects"])):
            out.append(f"- `{x['case']}` (expected {x['expected']}): {la}={x['predicted']}, {lb}={y['predicted']}")
    return out
L += ["", "## Cases whose outcome differs: checkpoint-1 vs final"] + (diffs(base, fin, "checkpoint", "final") or ["- none"])
L += ["", "## Cases whose outcome differs: final vs ablation (boundary points disabled)"] + (diffs(fin, ab, "final", "ablated") or ["- none"])
vb = json.loads((R / "ablation_no_model_claim_validation.json").read_text())
L += ["", f"Model claims rejected: final={fin['finding_quality']['model_claims_rejected']}, ablation(no validation)={vb['finding_quality']['model_claims_rejected']}.",
      "", "## Paired variants (final)"] + [f"- {p['a']} ({p['a_status']}) vs {p['b']} ({p['b_status']}): same outcome={p['same_outcome']}, same finding types={p['same_finding_types']}" for p in fin["paired_variants"]]
(R / "summary.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
